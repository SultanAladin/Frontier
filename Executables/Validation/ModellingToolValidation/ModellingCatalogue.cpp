const ToolBandDescriptor* ResolveModellingBands(int& BandCount)
{
    BandCount = 16;
    return ModellingBands;
}


const ToolProbeReadoutDescriptor* ResolveModellingProbe(unsigned int StratumBit)
{
    switch (StratumBit)
    {
        case ToolStratumNone: return &ProbeReadoutNone;
        case ToolStratumVertex: return &ProbeReadoutVertex;
        case ToolStratumEdge: return &ProbeReadoutEdge;
        case ToolStratumFace: return &ProbeReadoutFace;
        case ToolStratumLoop: return &ProbeReadoutLoop;
        case ToolStratumBorder: return &ProbeReadoutBorder;
        case ToolStratumObject: return &ProbeReadoutObject;
        default: break;
    }
    return nullptr;
}


const char* DescribeModellingStratum(unsigned int StratumBit)
{
    switch (StratumBit)
    {
        case ToolStratumNone: return "None";
        case ToolStratumVertex: return "Vertex";
        case ToolStratumEdge: return "Edge";
        case ToolStratumFace: return "Face";
        case ToolStratumLoop: return "Loop";
        case ToolStratumBorder: return "Border";
        case ToolStratumObject: return "Object";
        default: break;
    }
    return "Selection";
}


int ResolveModellingSelectedCount(unsigned int StratumBit)
{
    // 📝 The prototype's authored selection sizes, one per stratum — what the card is measured against in the validation host.
    switch (StratumBit)
    {
        case ToolStratumNone: return 0;
        case ToolStratumVertex: return 4;
        case ToolStratumEdge: return 6;
        case ToolStratumFace: return 8;
        case ToolStratumLoop: return 12;
        case ToolStratumBorder: return 8;
        case ToolStratumObject: return 1;
        default: break;
    }
    return 0;
}

